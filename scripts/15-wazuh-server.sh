#!/usr/bin/env bash
# Phase 15 - Wazuh server (Ubuntu Server 24.04)
# Run block by block, not as a whole file. See scripts/README.md.
#
# The Wazuh VM was installed on VMware NAT and then moved to vmnet5 (server network).

# --- 15.1 Find the current IP and MAC ---
# Run on: WAZUH (VM console)
ip -4 addr show
ip link show

# --- 15.2 Reserve 10.10.40.4 for Wazuh (PowerShell) ---
# Run on: SRV
#   Add-DhcpServerv4Reservation -ScopeId 10.10.40.0 -IPAddress 10.10.40.4 `
#       -ClientId "<WAZUH-MAC>" -Name "wazuh" -Description "Wazuh server"

# --- 15.3 Connect over SSH from SRV (PowerShell) ---
# Run on: SRV
#   ssh admintf@<WAZUH-CURRENT-IP>

# --- 15.4 Make Ubuntu honor the reservation ---
# Run on: WAZUH
# Ubuntu identifies itself to DHCP by DUID, not by MAC, so the MAC-based
# reservation is ignored until netplan is told to send the MAC.
sudo tee /etc/netplan/50-cloud-init.yaml > /dev/null <<'EOF'
network:
  version: 2
  ethernets:
    ens33:
      dhcp4: true
      dhcp-identifier: mac
EOF

echo "network: {config: disabled}" | sudo tee /etc/cloud/cloud.cfg.d/99-disable-network-config.cfg
sudo netplan apply
# The SSH session drops here. Reconnect from SRV with: ssh admintf@10.10.40.4

# --- 15.5 Prepare the system ---
# Run on: WAZUH
# The Ubuntu installer only uses half of the disk by default; lvextend + resize2fs
# grow the root filesystem to the whole disk, which the indexer needs.
sudo apt update && sudo apt upgrade -y
sudo timedatectl set-timezone America/Sao_Paulo
sudo lvextend -l +100%FREE /dev/ubuntu-vg/ubuntu-lv
sudo resize2fs /dev/ubuntu-vg/ubuntu-lv
df -h /

# --- 15.6 Install Wazuh (all-in-one: indexer, manager, dashboard) ---
# Run on: WAZUH
curl -sO https://packages.wazuh.com/4.14/wazuh-install.sh && sudo bash ./wazuh-install.sh -a

# Run on: WAZUH
# Dashboard passwords generated by the installer. Store them safely, never commit them.
sudo tar -O -xvf wazuh-install-files.tar wazuh-install-files/wazuh-passwords.txt

# Run on: WAZUH
# Disable the Wazuh repo so a routine apt upgrade cannot break the stack by version mismatch.
sudo sed -i "s/^deb /#deb /" /etc/apt/sources.list.d/wazuh.list
sudo apt update

# --- 15.7 Check ---
# Run on: WAZUH
sudo systemctl status wazuh-manager wazuh-indexer wazuh-dashboard --no-pager | grep -E "wazuh|Active"
# Dashboard: https://10.10.40.4 (user admin)

# --- 15.8 NFS test from phase 9 (read-only export) ---
# Run on: WAZUH
sudo apt install -y nfs-common
sudo mount -t nfs 10.10.40.3:/Publico /mnt
cat /mnt/leia-me.txt
sudo umount /mnt
